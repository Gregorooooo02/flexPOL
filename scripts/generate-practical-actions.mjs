#!/usr/bin/env node
// Generate only explicitly public navigation/action content, never scenario evaluation data.
// Usage: node scripts/generate-practical-actions.mjs [--check]
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const knowledge = join(root, 'knowledge');
const output = join(root, 'frontend/src/journey/connections.generated.ts');
const read = (file) => readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
const fail = (message) => { throw new Error(message); };
if (process.argv.slice(2).some((arg) => arg !== '--check')) fail('Usage: generate-practical-actions.mjs [--check]');

function exactKeys(value, keys, where) {
  if (!value || typeof value !== 'object' || Array.isArray(value)
    || Object.keys(value).some((key) => !keys.includes(key))
    || keys.some((key) => !(key in value))) fail(`${where}: unexpected or missing fields`);
}
function text(value, where) {
  if (typeof value !== 'string' || !value.trim() || value !== value.trim()) fail(`${where}: expected nonempty trimmed text`);
}
function references(values, known, where) {
  if (!Array.isArray(values) || new Set(values).size !== values.length || values.some((value) => !known.has(value))) {
    fail(`${where}: expected unique known references`);
  }
}

const chapters = [...read(join(knowledge, 'learning-chapters.md')).matchAll(/^## Chapter (\d+) — (.+)$/gm)]
  .map((match) => ({ number: Number(match[1]), title: match[2] }));
const lessons = [];
for (const directory of readdirSync(knowledge).filter((name) => /^chapter-\d+-/.test(name)).sort()) {
  for (const file of readdirSync(join(knowledge, directory)).filter((name) => /^\d+-\d+-.*\.md$/.test(name)).sort()) {
    const heading = read(join(knowledge, directory, file)).match(/^# (\d+\.\d+) (.+)$/m);
    if (!heading) fail(`${directory}/${file}: missing lesson heading`);
    lessons.push({ code: heading[1], title: heading[2] });
  }
}
const scenarioSource = JSON.parse(read(join(knowledge, 'sandbox-scenarios.json')));
// Explicit projection: raw scenario fields must never be copied into generated output.
const scenarios = scenarioSource.scenarios.map(({ id, code, title }) => ({ slug: id, code, title }));
const source = JSON.parse(read(join(knowledge, 'practical-actions.json')));
exactKeys(source, ['version', 'actions'], 'catalogue');
if (source.version !== 1 || !Array.isArray(source.actions) || !source.actions.length) fail('Unsupported/empty catalogue');
const lessonCodes = new Set(lessons.map(({ code }) => code));
const chapterNumbers = new Set(chapters.map(({ number }) => number));
const scenarioSlugs = new Set(scenarios.map(({ slug }) => slug));
const tools = new Set(['goal-planner', 'emergency-buffer', 'fee-impact']);
const sections = new Set(['goal', 'liquidity', 'risk', 'knowledge', 'review']);
const ids = new Set();
for (const action of source.actions) {
  exactKeys(action, ['id', 'concept', 'title', 'description', 'relevance', 'lessonCodes', 'chapterNumbers', 'scenarioSlugs', 'destination'], 'action');
  for (const key of ['id', 'concept', 'title', 'description', 'relevance']) text(action[key], `${action.id}.${key}`);
  if (!/^[a-z][a-z0-9-]*$/.test(action.id) || ids.has(action.id)) fail(`Invalid/duplicate action ID: ${action.id}`);
  ids.add(action.id);
  references(action.lessonCodes, lessonCodes, `${action.id}.lessonCodes`);
  references(action.chapterNumbers, chapterNumbers, `${action.id}.chapterNumbers`);
  references(action.scenarioSlugs, scenarioSlugs, `${action.id}.scenarioSlugs`);
  exactKeys(action.destination, ['kind', 'id'], `${action.id}.destination`);
  const allowed = action.destination.kind === 'tool' ? tools : action.destination.kind === 'profile' ? sections : null;
  if (!allowed?.has(action.destination.id)) fail(`${action.id}: unknown destination`);
}

const generated = `// Generated by scripts/generate-practical-actions.mjs. Do not edit.\nimport type { PracticalConnection } from './types';\n\nexport const PUBLIC_CONTENT = ${JSON.stringify({ version: source.version, chapters, lessons, scenarios }, null, 2)} as const;\n\nexport const PRACTICAL_CONNECTIONS = ${JSON.stringify(source.actions, null, 2)} as const satisfies readonly PracticalConnection[];\n`;
const guidance = JSON.parse(read(join(knowledge, 'roadmap-guidance.json')));
exactKeys(guidance, ['version', 'observations'], 'roadmap guidance');
const guidanceIds = ['missing-goal', 'unanswered', 'early-access', 'capacity-tension', 'timing-tension', 'not-sure', 'starting-knowledge', 'past-goal', 'review-note'];
if (guidance.version !== 1) fail('Unsupported guidance version');
exactKeys(guidance.observations, guidanceIds, 'observations');
for (const [id, observation] of Object.entries(guidance.observations)) {
  exactKeys(observation, ['title', 'description', 'actionId', 'reason'], id);
  for (const [key, value] of Object.entries(observation)) text(value, `${id}.${key}`);
  if (!ids.has(observation.actionId)) fail(`${id}: unknown practical action`);
}
const guidanceOutput = join(root, 'frontend/src/roadmap/guidance.generated.ts');
const generatedGuidance = `// Generated by scripts/generate-practical-actions.mjs. Do not edit.\nexport const ROADMAP_GUIDANCE = ${JSON.stringify(guidance.observations, null, 2)} as const;\n`;
const outputs = [[output, generated], [guidanceOutput, generatedGuidance]];
if (process.argv.includes('--check')) {
  for (const [path, content] of outputs) {
    let existing = '';
    try { existing = read(path); } catch { /* Missing output is stale too. */ }
    if (existing !== content) fail('Practical connections/guidance are stale. Run node scripts/generate-practical-actions.mjs');
  }
  console.log('Practical connections and roadmap guidance are valid and up to date.');
} else {
  for (const [path, content] of outputs) writeFileSync(path, content);
  console.log(`Generated ${source.actions.length} public practical connections and ${guidanceIds.length} roadmap observations.`);
}
