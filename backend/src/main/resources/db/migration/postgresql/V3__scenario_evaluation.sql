-- Scenario result evaluation (commit d7dd462): suitable instruments, share ranges and the
-- explanation shown with the result. Generated from the entities like V1.

-- Existing rows get placeholder values; R__Seed_content reloads every scenario right after.
alter table scenario add column min_instruments integer not null default 0;
alter table scenario alter column min_instruments drop default;
alter table scenario add column evaluation_explanation varchar(1000) not null default '';
alter table scenario alter column evaluation_explanation drop default;

create table scenario_share_range (
    each_instrument boolean not null,
    includes_cash boolean not null,
    max_share numeric(5,4) not null,
    min_share numeric(5,4) not null,
    sort_order integer not null,
    id bigint generated by default as identity,
    scenario_id bigint not null,
    label varchar(255) not null,
    primary key (id),
    unique (scenario_id, sort_order)
);

create table scenario_share_range_instrument (
    sort_order integer not null check ((sort_order>=0)),
    instrument_id bigint not null,
    share_range_id bigint not null,
    primary key (sort_order, share_range_id)
);

create table scenario_suitable_instrument (
    sort_order integer not null check ((sort_order>=0)),
    instrument_id bigint not null,
    scenario_id bigint not null,
    primary key (sort_order, scenario_id)
);

