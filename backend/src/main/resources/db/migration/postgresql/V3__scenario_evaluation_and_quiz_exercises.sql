alter table scenario
    alter column min_instruments drop default,
    alter column evaluation_explanation drop default;

create table scenario_suitable_instrument (
    scenario_id bigint not null references scenario,
    instrument_id bigint not null references instrument,
    sort_order integer not null check (sort_order >= 0),
    primary key (sort_order, scenario_id)
);

create table scenario_share_range (
    id bigint generated by default as identity primary key,
    scenario_id bigint not null references scenario,
    sort_order integer not null,
    label varchar(255) not null,
    includes_cash boolean not null,
    each_instrument boolean not null,
    min_share numeric(5,4) not null,
    max_share numeric(5,4) not null,
    unique (scenario_id, sort_order)
);

create table scenario_share_range_instrument (
    share_range_id bigint not null references scenario_share_range,
    instrument_id bigint not null references instrument,
    sort_order integer not null check (sort_order >= 0),
    primary key (sort_order, share_range_id)
);

alter table scenario_suitable_instrument enable row level security;
alter table scenario_share_range enable row level security;
alter table scenario_share_range_instrument enable row level security;
