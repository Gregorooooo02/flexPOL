create table answer_option (
    is_correct boolean not null,
    label varchar(1) not null,
    id bigint generated by default as identity,
    question_id bigint not null,
    text varchar(1000) not null,
    primary key (id),
    unique (question_id, label)
);

create table app_user (
    id bigint generated by default as identity,
    username varchar(50) not null,
    email varchar(254) not null unique,
    primary key (id)
);

create table attempt_answer (
    correct boolean not null,
    attempt_id bigint not null,
    id bigint generated by default as identity,
    question_id bigint not null,
    selected_option_id bigint not null,
    primary key (id),
    unique (attempt_id, question_id)
);

create table chapter (
    sort_order integer not null unique,
    id bigint generated by default as identity,
    objective varchar(1000),
    mission_description varchar(2000),
    mission_title varchar(255),
    title varchar(255) not null,
    primary key (id)
);

create table coach_conversation (
    created_at timestamp(6) with time zone not null,
    user_id bigint not null,
    id varchar(36) not null,
    primary key (id)
);

create table historical_observation (
    observation_date date not null,
    observation_value numeric(24,8) not null,
    original_date date not null,
    id bigint not null,
    instrument_id bigint not null,
    primary key (id),
    constraint uk_historical_observation_instrument_date unique (instrument_id, observation_date)
);

create table instrument (
    currency varchar(3) not null,
    history_rebased boolean not null,
    id bigint not null,
    risk_level varchar(32) not null check ((risk_level in ('LOW','MEDIUM','HIGH'))),
    asset_class varchar(64) not null check ((asset_class in ('STOCK','EQUITY_ETF','DEPOSIT'))),
    history_value_type varchar(64) not null check ((history_value_type in ('PRICE','TOTAL_RETURN_INDEX','ACCRUED_VALUE_INDEX'))),
    description varchar(2000),
    history_description varchar(2000),
    history_source varchar(255) not null,
    name varchar(255) not null,
    primary key (id)
);

create table question (
    sort_order integer not null,
    id bigint generated by default as identity,
    quiz_id bigint not null,
    source_subchapter_id bigint,
    prompt varchar(1000) not null,
    explanation varchar(2000),
    primary key (id),
    unique (quiz_id, sort_order)
);

create table quiz (
    pass_mark integer,
    chapter_id bigint not null,
    id bigint generated by default as identity,
    subchapter_id bigint unique,
    quiz_type varchar(20) not null check ((quiz_type in ('CONTROL','FINAL'))),
    title varchar(255) not null,
    primary key (id)
);

create table quiz_attempt (
    passed boolean,
    score integer,
    completed_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    quiz_id bigint not null,
    started_at timestamp(6) with time zone not null,
    user_id bigint not null,
    primary key (id)
);

